-- 0067_quiz_entries.sql — Know Your Flames: a quiz anyone can enter and nobody
-- can read.
--
-- WHY. The Flames play Egypt twice in November 2026 (Cairo on the 13th,
-- Lilongwe on the 17th), and the site wants the visits that come with it. The
-- campaign is a three-question quiz whose answers are all on the Flames pages,
-- with a prize draw per round: jerseys for the first, match tickets for the
-- second. A draw needs a way to reach the winner, so this is the first table
-- in the schema that holds a member of the public's phone number.
--
-- WHAT THIS DOES. Three tables and one write path.
--
--   * quizzes       the two rounds and their windows. The window is enforced
--                   HERE, on the database clock; the page reads the same
--                   times from src/quiz.py only to decide what to show.
--   * quiz_entries  one row per phone number per round.
--   * quiz_draws    what scripts/quiz.py drew, from how big a pool, so a
--                   draw can be shown to have happened the way it was said to.
--
-- submit_quiz_entry is the only way in, and it is granted to anon.
--
-- THE TRADE, stated plainly, because 0052 refused exactly this. That
-- migration would not let an unauthenticated browser record an error, on the
-- grounds that an unauthenticated insert endpoint on a public database is a
-- way to fill it. That is still true. Here the endpoint IS the product: a quiz
-- you have to sign in to enter is a quiz nobody enters. So the endpoint is
-- made as small as it can be instead:
--
--   * one function, no table grants at all — anon cannot SELECT, INSERT,
--     UPDATE or DELETE anything, and cannot read back even its own entry;
--   * the window is the database's, so a page left open past the close is
--     refused rather than trusted;
--   * one entry per phone number per round, a unique index rather than a
--     check, so two taps on a slow connection cannot make two rows;
--   * a cap on rows per round, so the worst a script with random numbers can
--     do is end a round early, never grow the database without bound.
--
-- There is deliberately NO per-address rate limit. Malawi's mobile networks
-- put many subscribers behind one address (carrier-grade NAT), so a limit per
-- IP would refuse real fans on the same network as each other. The cap and the
-- unique phone are the guards.
--
-- NONE OF THIS REACHES THE SITE. src/source_supabase.py reads a fixed list of
-- tabs and these are not among them, so no entry can land in data/canonical/,
-- which is public. That is the same reason matches.notes stays out of it.

begin;

create table public.quizzes (
  quiz_id      text primary key,
  title        text not null,
  opens_at     timestamptz not null,
  closes_at    timestamptz not null,
  -- Every question id the page asks. An entry must answer all of them and
  -- nothing else, so a page and a database that disagree about the questions
  -- fail on the first entry rather than silently at the draw.
  question_ids text[] not null,
  check (closes_at > opens_at)
);

comment on table public.quizzes is
  'Know Your Flames rounds (0067). The window is enforced by '
  'submit_quiz_entry; src/quiz.py carries the same times for the page.';

-- The same times as src/quiz.py. tests/test_quiz.py reads this file and fails
-- if the two disagree.
insert into public.quizzes (quiz_id, title, opens_at, closes_at, question_ids)
values
  ('flames-egypt-1', 'Know Your Flames: Round 1',
   '2026-11-11 00:00+02', '2026-11-13 18:00+02',
   array['last-win', 'ss-scorers', 'japan']),
  ('flames-egypt-2', 'Know Your Flames: Round 2',
   '2026-11-13 23:00+02', '2026-11-16 15:00+02',
   array['cairo', 'venue', 'matches']);

create table public.quiz_entries (
  id              bigint generated by default as identity primary key,
  quiz_id         text not null references public.quizzes (quiz_id),
  name            text not null,
  -- Normalised by quiz_normalise_phone: +265 and nine digits for a Malawian
  -- number however it was typed, so "0991 234 567" and "+265991234567" are the
  -- same person and the unique index below means something.
  phone           text not null,
  email           text not null default '',
  -- {question_id: chosen value}. Not marked here: the draw marks it, because
  -- one answer (the Cairo score) does not exist until a match has been played.
  answers         jsonb not null,
  -- Required to enter: may we contact you about this prize.
  consent_contact boolean not null,
  -- Optional, and separate on purpose: entering a draw is not agreeing to be
  -- marketed to. This is the subscriber list.
  opt_in_updates  boolean not null default false,
  created_at      timestamptz not null default now(),
  unique (quiz_id, phone)
);

comment on table public.quiz_entries is
  'Quiz entries (0067): a member of the public''s name and phone number. '
  'Written only by submit_quiz_entry, read only with the secret key. Never in '
  'the Dataset and never in data/canonical/.';

create table public.quiz_draws (
  id         bigint generated by default as identity primary key,
  quiz_id    text not null references public.quizzes (quiz_id),
  drawn_at   timestamptz not null default now(),
  entries    integer not null,   -- every entry in the round
  pool       integer not null,   -- the ones with every answer right
  winners    bigint[] not null,  -- quiz_entries.id, in the order drawn
  answer_key jsonb not null      -- what "right" meant, Cairo score included
);

comment on table public.quiz_draws is
  'One row per draw run by scripts/quiz.py: the pool, the key and who won.';

alter table public.quizzes      enable row level security;
alter table public.quiz_entries enable row level security;
alter table public.quiz_draws   enable row level security;

-- No policies, and the grants taken back as well: this project's default
-- privileges grant new objects to anon (0048), and RLS with no policy is one
-- guard where two cost nothing. The secret key bypasses both, which is how
-- scripts/quiz.py and the Supabase dashboard read them.
revoke all on public.quizzes, public.quiz_entries, public.quiz_draws
  from anon, authenticated;


-- ── quiz_normalise_phone ─────────────────────────────────────────────────────
-- static/quiz/rules.js normalisePhone is the same function, so the page can
-- say "that does not look like a phone number" before the round trip. This one
-- is the one that counts.
--
--   0991 234 567 / 991234567 / 265991234567 / +265 991 234 567 → +265991234567
--   +44 7700 900123 / 0044 7700 900123                         → +447700900123
--
-- A fan abroad can enter; a Malawian number must be nine digits after 265.

create or replace function public.quiz_normalise_phone(p_raw text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_plus   boolean;
  v_digits text;
begin
  if p_raw is null then
    return null;
  end if;
  v_plus := left(btrim(p_raw), 1) = '+';
  v_digits := regexp_replace(p_raw, '[^0-9]', '', 'g');
  if not v_plus and left(v_digits, 2) = '00' then
    v_plus := true;
    v_digits := substr(v_digits, 3);
  end if;

  if v_plus or (left(v_digits, 3) = '265' and length(v_digits) = 12) then
    if left(v_digits, 3) = '265' then
      return case when length(v_digits) = 12 then '+' || v_digits end;
    end if;
    return case when v_plus and length(v_digits) between 8 and 15
                then '+' || v_digits end;
  end if;
  if left(v_digits, 1) = '0' and length(v_digits) = 10 then
    return '+265' || substr(v_digits, 2);
  end if;
  if length(v_digits) = 9 then
    return '+265' || v_digits;
  end if;
  return null;
end;
$$;

revoke execute on function public.quiz_normalise_phone(text)
  from public, anon, authenticated;


-- ── submit_quiz_entry ────────────────────────────────────────────────────────
-- RETURNS AN ANSWER, NEVER RAISES for anything a person could have done. The
-- page shows `message` as it stands, so every message is a sentence for a fan
-- on a phone, not for a developer:
--
--   {ok: true,  status: 'entered'}
--   {ok: false, status: 'duplicate' | 'not_open' | 'closed' | 'invalid'
--               | 'unknown', message: '…'}
--
-- `p_website` is a honeypot: a field the page hides from people. A form-filling
-- bot fills it, and is told it entered.

create or replace function public.submit_quiz_entry(
  p_quiz    text,
  p_name    text,
  p_phone   text,
  p_email   text    default '',
  p_answers jsonb   default '{}'::jsonb,
  p_consent boolean default false,
  p_updates boolean default false,
  p_website text    default ''
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_quiz  public.quizzes;
  v_name  text;
  v_phone text;
  v_email text;
  v_keys  text[];
begin
  if coalesce(p_website, '') <> '' then
    return jsonb_build_object('ok', true, 'status', 'entered');
  end if;

  select * into v_quiz from public.quizzes q where q.quiz_id = p_quiz;
  if not found then
    return jsonb_build_object('ok', false, 'status', 'unknown',
      'message', 'That quiz does not exist. Reload the page and try again.');
  end if;
  if now() < v_quiz.opens_at then
    return jsonb_build_object('ok', false, 'status', 'not_open',
      'message', 'This round has not opened yet.');
  end if;
  if now() >= v_quiz.closes_at then
    return jsonb_build_object('ok', false, 'status', 'closed',
      'message', 'Sorry, this round has closed.');
  end if;

  v_name := left(btrim(regexp_replace(coalesce(p_name, ''), '\s+', ' ', 'g')),
                 80);
  if length(v_name) < 2 then
    return jsonb_build_object('ok', false, 'status', 'invalid',
      'message', 'Please enter your name.');
  end if;

  v_phone := public.quiz_normalise_phone(p_phone);
  if v_phone is null then
    return jsonb_build_object('ok', false, 'status', 'invalid',
      'message', 'Please enter a phone number we can reach you on, '
                 'like 0991 234 567.');
  end if;

  v_email := lower(btrim(coalesce(p_email, '')));
  if v_email <> '' and (length(v_email) > 120
                        or v_email !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$') then
    return jsonb_build_object('ok', false, 'status', 'invalid',
      'message', 'That email address does not look right. '
                 'Fix it, or leave it empty.');
  end if;

  if not coalesce(p_consent, false) then
    return jsonb_build_object('ok', false, 'status', 'invalid',
      'message', 'Please tick the box agreeing to the rules, '
                 'so we can contact you if you win.');
  end if;

  -- Every question answered, nothing else, every answer a short string.
  if jsonb_typeof(p_answers) is distinct from 'object' then
    return jsonb_build_object('ok', false, 'status', 'invalid',
      'message', 'Please answer every question.');
  end if;
  select coalesce(array_agg(k order by k), '{}') into v_keys
  from jsonb_object_keys(p_answers) k;
  if v_keys is distinct from (select array_agg(q order by q)
                              from unnest(v_quiz.question_ids) q)
     or exists (select 1 from jsonb_each(p_answers) e
                where jsonb_typeof(e.value) <> 'string'
                   or length(e.value #>> '{}') not between 1 and 20) then
    return jsonb_build_object('ok', false, 'status', 'invalid',
      'message', 'Please answer every question.');
  end if;

  if (select count(*) from public.quiz_entries e
      where e.quiz_id = v_quiz.quiz_id) >= 50000 then
    return jsonb_build_object('ok', false, 'status', 'closed',
      'message', 'Sorry, this round is full.');
  end if;

  insert into public.quiz_entries
    (quiz_id, name, phone, email, answers, consent_contact, opt_in_updates)
  values
    (v_quiz.quiz_id, v_name, v_phone, v_email, p_answers, true,
     coalesce(p_updates, false))
  on conflict (quiz_id, phone) do nothing;
  if not found then
    return jsonb_build_object('ok', false, 'status', 'duplicate',
      'message', 'This phone number has already entered this round. '
                 'One entry per number. Good luck!');
  end if;

  return jsonb_build_object('ok', true, 'status', 'entered');
end;
$$;

comment on function public.submit_quiz_entry(
  text, text, text, text, jsonb, boolean, boolean, text) is
  'Enter a Know Your Flames round (0067). Granted to anon; never raises for '
  'bad input, returns {ok, status, message}.';

revoke execute on function public.submit_quiz_entry(
  text, text, text, text, jsonb, boolean, boolean, text) from public;
grant execute on function public.submit_quiz_entry(
  text, text, text, text, jsonb, boolean, boolean, text) to anon, authenticated;

commit;
