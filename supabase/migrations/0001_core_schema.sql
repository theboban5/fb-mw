-- ── entries ──────────────────────────────────────────────────────────────────
-- A team's participation in one competition+season. Standings iterate entries,
-- so a team with zero matches still appears in the table.

create table public.entries (
  entry_id           text primary key,
  competition_id     text not null references public.competitions (competition_id),
  season_id          text not null references public.seasons (season_id),
  team_id            text not null references public.teams (team_id),
  "group"            text not null default '',
  points_adjustment  integer not null default 0,   -- may be negative
