-- 0001_core_schema.sql — the existing EveryLeague data model, ported to Postgres.
--
-- This is a PORT, not a redesign. DATA_MODEL.md is authoritative: canonical
-- text ids (MW_BULL, MW_BULL_M1, MW_SL_2627_001, CAF_MW_000123) stay the
-- primary keys, the enum vocabularies are unchanged, and the two schemas —
-- the league tables and the nt_* national-team tables — stay separate, sharing
-- no ids, exactly as they do in the spreadsheet.
--
-- Three conventions run through every table:
--
--   * `ord` preserves SHEET ROW ORDER, and it is load-bearing, not cosmetic.
--     src/adapt.py numbers MatchView.row from the row's position in the
--     Dataset, and src/standings.py and adapt.cup_rounds sort by it; the
--     validator's two-legged-tie pairing walks ds.matches in insertion order
--     to decide which leg is the decider. Postgres has no inherent row order,
--     so every read that rebuilds a tab MUST `order by ord`. Without it,
--     same-date fixtures silently reshuffle on the rendered pages.
--
--   * Nullable FK columns hold NULL for "absent"; every other text column is
--     `not null default ''`. The Python Dataset reads a blank cell as "", so
--     the CSV emitter coalesces NULL -> ''. Keeping that split means only FK
--     columns ever need coalescing, and a NULL can never be mistaken for a
--     real id.
--
--   * Single-row/single-column integrity lives here as constraints; anything
--     needing cross-row or cross-table context stays in validate.py. The
--     mapping to validate.py's numbered checks is noted per constraint.
--
-- RLS is enabled on every table with read-only public policies. No write
-- policy exists yet: until 0002 adds reporters, the only writer is the secret
-- key (which bypasses RLS), used by scripts/import_canonical.py and CI.

begin;

