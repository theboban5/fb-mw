-- Whole knockout trees, including ties we are not in (that is how the WAFCON
-- bracket renders). Our own ties additionally carry nt_match_id, and then
-- nt_matches owns the result — the score columns here must stay blank.
create table public.nt_knockout (
  tie_id            text primary key,
  competition_name  text not null check (competition_name <> ''),
  stage             text not null
                    check (stage in ('r64', 'r32', 'r16', 'qf', 'sf', 'final', '3p')),
  slot              integer not null default 0,
  home_name         text not null default '',
  away_name         text not null default '',
  -- 'winner:<tie_id>' / 'loser:<tie_id>' — a slot fed by an earlier tie. That
  -- the named tie exists, is not this one, and is in the same competition are
  -- cross-row rules in validate.py check 9.
  home_from         text not null default ''
                    check (home_from = '' or home_from ~ '^(winner|loser):.+$'),
  away_from         text not null default ''
                    check (away_from = '' or away_from ~ '^(winner|loser):.+$'),
  home_score        integer check (home_score >= 0),
  away_score        integer check (away_score >= 0),
  home_pens         integer check (home_pens >= 0),
  away_pens         integer check (away_pens >= 0),
  extra_time        boolean not null default false,
  date              text not null default '',
  kickoff           text not null default '',
  venue             text not null default '',
  city              text not null default '',
  status            text not null default 'scheduled'
                    check (status in ('scheduled', 'played', 'awarded')),
  nt_match_id       text references public.nt_matches (match_id),
  ord               bigint generated by default as identity,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  constraint nt_knockout_score_is_a_pair
    check ((home_score is null) = (away_score is null)),
  constraint nt_knockout_pens_are_a_pair
    check ((home_pens is null) = (away_pens is null)),
  constraint nt_knockout_pens_have_a_winner
    check (home_pens is null or home_pens <> away_pens),
  -- nt_matches owns the result for our own ties, so a copy here could
  -- contradict it with nothing to say which is right (validate.py check 9).
  constraint nt_knockout_linked_tie_has_no_score
    check (nt_match_id is null
           or (home_score is null and away_score is null
               and home_pens is null and away_pens is null)),
  unique (competition_name, stage, slot)
);


