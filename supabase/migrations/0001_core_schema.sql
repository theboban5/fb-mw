-- ── matches ──────────────────────────────────────────────────────────────────

create table public.matches (
  match_id        text primary key,

  -- Unguessable id for reporter deep links (/report/m/<public_id>). Added
  -- ALONGSIDE match_id, which stays the canonical opaque key everywhere else —
  -- per DATA_MODEL.md, ids are never regenerated. Secrecy of this value is not
  -- authorization; the reporter's assignment is.
  public_id       uuid not null unique default gen_random_uuid(),

  competition_id  text not null references public.competitions (competition_id),
  season_id       text not null references public.seasons (season_id),

  -- Free-form md_<n> on leagues; on a type=cup competition it must come from
  -- the knockout vocabulary (r64|r32|r16|qf|sf|final|3p). That rule needs
  -- competitions.type, so it stays in validate.py check 7.
  stage           text not null default '',
  matchday        integer check (matchday >= 0),

  -- NULL = fixture not yet scheduled to a day (876 such rows today). It is the
  -- Malawi calendar date, which is what makes "today's fixtures" a plain
  -- equality test for the reporter home screen.
  date            date,
  -- Kept as text, not `time`: the sheet holds both HH:MM and Sheets' HH:MM:SS
  -- and adapt.clock normalizes either (and anything unreadable) for display.
  -- Always Malawi time — CAT, UTC+2, no DST.
  kickoff         text not null default ''
                  check (kickoff = '' or kickoff ~ '^[0-9]{1,2}:[0-9]{2}(:[0-9]{2})?$'),

  venue_id        text references public.venues (venue_id),
  home_team_id    text not null references public.teams (team_id),
  away_team_id    text not null references public.teams (team_id),
  home_goals      integer check (home_goals >= 0),
  away_goals      integer check (away_goals >= 0),

  -- The existing vocabulary, unchanged. The reporter UI displays "Full time"
  -- but publishes status='played' — there is deliberately no competing
  -- 'full_time' value, because standings, results and every renderer key off
  -- these six. played and awarded are what count toward a table.
  status          text not null
                  check (status in ('scheduled', 'played', 'postponed',
                                    'abandoned', 'awarded', 'cancelled')),

  -- Reserved for live reporting, which is NOT built. Kept off `status` so the
  -- existing vocabulary never has to grow a value the renderers don't know:
  -- a live match is still status='scheduled' with live_state set. Nothing
  -- reads this yet.
  live_state      text check (live_state in ('live', 'half_time')),

  awarded_note    text not null default '',

  -- Provenance, already in the model. Reporter submissions set
  -- source_type='reporter', reported_by and reported_at (see 0003).
  source_type     text not null default 'unknown'
                  check (source_type in ('reporter', 'rfa', 'fa', 'club',
                                         'facebook', 'newspaper', 'whatsapp',
                                         'backfill', 'placeholder', 'unknown')),
  source_ref      text not null default '',
  reported_by     text references public.reporters (reporter_id),
  reported_at     timestamptz,
  confidence      text not null default 'unconfirmed'
                  check (confidence in ('unconfirmed', 'confirmed', 'official')),
  verified_by     text references public.reporters (reporter_id),
  verified_at     timestamptz,

  -- Knockout-only. That they appear only on a cup, only on a tie's deciding
  -- leg, and only against a level score or aggregate are all cross-row rules
  -- and stay in validate.py check 7.
  extra_time      boolean not null default false,
  home_pens       integer check (home_pens >= 0),
  away_pens       integer check (away_pens >= 0),

  ord             bigint generated by default as identity,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),

  -- validate.py check 4, in full.
  constraint matches_no_self_play
    check (home_team_id <> away_team_id),
  constraint matches_score_is_a_pair
    check ((home_goals is null) = (away_goals is null)),
  constraint matches_played_has_score
    check (status not in ('played', 'awarded') or home_goals is not null),
  constraint matches_scheduled_has_no_score
    check (status <> 'scheduled' or home_goals is null),

  -- validate.py check 7, the parts that need only this row.
  constraint matches_pens_are_a_pair
    check ((home_pens is null) = (away_pens is null)),
  constraint matches_pens_have_a_winner
    check (home_pens is null or home_pens <> away_pens),

  -- validate.py check 3, now a database guarantee: a match cannot name a team
  -- that has no entries row for its competition+season. The plain FKs on
  -- home_team_id/away_team_id above are implied by these but kept, because a
  -- match referencing teams is a fact about the model, not an implementation
  -- detail of how entries happens to be keyed.
  constraint matches_home_team_entered
    foreign key (competition_id, season_id, home_team_id)
    references public.entries (competition_id, season_id, team_id),
  constraint matches_away_team_entered
    foreign key (competition_id, season_id, away_team_id)
    references public.entries (competition_id, season_id, team_id)
);

comment on column public.matches.public_id is
  'Deep-link id for /report/m/<public_id>. Not a capability: RLS authorizes.';
comment on column public.matches.live_state is
  'Reserved for live reporting; nothing reads it. Keeps status'' six values intact.';


-- ── goals ────────────────────────────────────────────────────────────────────
-- team_id is the team the goal COUNTED FOR — for an own goal that is the
-- beneficiary, with the defender as player_id. Own goals therefore never
-- appear in scorer tables but do count toward the score.

create table public.goals (
  goal_id              text primary key,
  match_id             text not null
                       references public.matches (match_id) on delete cascade,
  team_id              text not null references public.teams (team_id),
  player_id            text not null references public.players (player_id),

  -- The sheet's denormalized name column. The build ignores it entirely
  -- (names resolve via player_id -> players); it is carried over so the
  -- migration loses nothing, and it stays unread.
  player_name          text not null default '',

  -- NEW. What a reporter typed when EveryLeague has no canonical player yet.
  -- Paired with player_id = CAF_MW_UNKNOWN, so the goal counts toward the
  -- score and the name can be shown on the match page, while the scorer
  -- rankings — which already drop CAF_MW_UNKNOWN — stay canonical. Kept after
  -- reconciliation as provenance, hence no constraint tying it to UNKNOWN.
  reported_player_name text not null default '',

  -- Display string, not a number: '45+5' occurs in the data.
  minute               text not null default '',
  stoppage             text not null default '',
  period               text not null default ''
                       check (period in ('', '1h', '2h', 'et1', 'et2')),
  goal_type            text not null default ''
                       check (goal_type in ('', 'open_play', 'penalty',
                                            'free_kick', 'header', 'own_goal')),
  assist_player_id     text references public.players (player_id),
  source_type          text not null default 'unknown'
                       check (source_type in ('reporter', 'rfa', 'fa', 'club',
                                              'facebook', 'newspaper', 'whatsapp',
                                              'backfill', 'placeholder', 'unknown')),
  source_ref           text not null default '',
  reported_by          text references public.reporters (reporter_id),
  reported_at          timestamptz,
  confidence           text not null default 'unconfirmed'
                       check (confidence in ('unconfirmed', 'confirmed', 'official')),
  verified_by          text references public.reporters (reporter_id),
  verified_at          timestamptz,
  ord                  bigint generated by default as identity,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);

