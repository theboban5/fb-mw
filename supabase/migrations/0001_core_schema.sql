-- ── clubs ────────────────────────────────────────────────────────────────────
-- The institution (Nyasa Big Bullets). One row per club; a club's squads are
-- rows in `teams`. Never collapse the two.

create table public.clubs (
  club_id             text primary key,
  name                text not null check (name <> ''),
  short_name          text not null default '',
  city                text not null default '',
  region              text not null default '',
  -- Free text, not an integer: 137 of 138 rows are blank and the Dataset
  -- reads it as a string.
  founded             text not null default '',
  crest               text not null default '',
  status              text not null default '',
  successor_club_id   text references public.clubs (club_id),
  notes               text not null default '',
  ord                 bigint generated by default as identity,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);

comment on table public.clubs is
  'The club as an institution. Its squads are rows in teams — do not merge.';


-- ── teams ────────────────────────────────────────────────────────────────────
-- A squad of a club. gender + age_group + squad_level live here, so MW_BULL_M1
-- is the men's first team and MW_BULL_W1 the women's.

create table public.teams (
  team_id       text primary key,
  club_id       text not null references public.clubs (club_id),
  gender        text not null check (gender in ('m', 'w')),
  age_group     text not null
                check (age_group in ('senior', 'u20', 'u19', 'u17', 'u16', 'u15')),
  squad_level   integer not null check (squad_level between 1 and 4),
  display_name  text not null check (display_name <> ''),
  -- The old per-league sheet code (SL_BE, CRFA_AR). PUBLIC URLS AND LOGO
  -- FILENAMES ARE KEYED BY THIS — /{slug}/clubs/SL_BE.html is live. 32 of 157
  -- rows are blank, and adapt.py falls back to team_id for those.
  legacy_code   text not null default '',
  status        text not null default '',
  ord           bigint generated by default as identity,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

comment on column public.teams.legacy_code is
  'Public URL and logo key. Changing a value breaks a live page.';


