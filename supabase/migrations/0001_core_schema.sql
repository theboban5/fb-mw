-- ── seasons ──────────────────────────────────────────────────────────────────
-- Exactly one row may be status=active. That row — never the system clock — is
-- what the build treats as the current season (dataset.Dataset.active_season).

create table public.seasons (
  season_id   text primary key,
  country     text not null default '',
  label       text not null check (label <> ''),
  start_date  date not null,
  end_date    date not null,
  status      text not null check (status in ('active', 'complete')),
  ord         bigint generated by default as identity,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint seasons_dates_ordered check (start_date <= end_date)
);

-- dataset.active_season() raises unless exactly one row is active. Enforcing
-- "at most one" here turns the silent half of that into a database error;
-- "at least one" stays in Python, where an empty table is also a failure.
create unique index seasons_one_active
  on public.seasons ((status)) where status = 'active';


