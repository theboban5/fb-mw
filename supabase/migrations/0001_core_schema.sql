-- One row per match from OUR team's perspective: `opponent` is a display name,
-- not a code, so there is nothing to resolve it against.
create table public.nt_matches (
  match_id           text primary key,
  team_code          text not null references public.nt_teams (team_code),
  -- TEXT, not date: the literal 'tbd' is a legal value (6 rows today) meaning
  -- "fixture agreed, no date yet"; it renders as "Date TBC". Anything else
  -- must be strict YYYY-MM-DD.
  date               text not null default ''
                     check (date = '' or lower(date) in ('tbd', 'tba')
                            or date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),
  competition        text not null default '',
  opponent           text not null default '',
  home_away          text not null default '',
  neutral            boolean not null default false,
  venue              text not null default '',
  -- Malawi time, like every other kickoff on the site.
  kickoff            text not null default ''
                     check (kickoff = '' or lower(kickoff) in ('tbd', 'tba')
                            or kickoff ~ '^[0-9]{1,2}:[0-9]{2}(:[0-9]{2})?$'),
  city               text not null default '',
  country            text not null default '',
  team_score         integer check (team_score >= 0),
  opponent_score     integer check (opponent_score >= 0),
  -- Narrower than the league vocabulary on purpose: no postponed/abandoned
  -- rows exist yet and nt_page has no rendering for them.
  status             text not null check (status in ('scheduled', 'played', 'awarded')),
  coach              text not null default '',
  extra_time         boolean not null default false,
  penalty_shootout   text not null default '',
  extra_time_result  text not null default '',
  ord                bigint generated by default as identity,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  constraint nt_matches_score_is_a_pair
    check ((team_score is null) = (opponent_score is null)),
  constraint nt_matches_played_has_score
    check (status not in ('played', 'awarded') or team_score is not null),
  constraint nt_matches_scheduled_has_no_score
    check (status <> 'scheduled' or team_score is null)
);


