-- 0071_update_signups.sql — "Tell me about the next one": a sign-up box on
-- /quiz/ for future quizzes and events.
--
-- WHAT WAS WRONG. The only way onto EveryLeague's list was the "send me
-- updates" box inside a quiz entry (0067's opt_in_updates). Know Your Flames
-- is over, so from now on a fan arriving at /quiz/ from the banner, the
-- winners or a shared link had no way to say "tell me next time" at all. The
-- 228 people who ticked that box are the list; nothing could add a 229th.
--
-- WHAT THIS DOES. One table and one write path, 0067's arrangement exactly:
--
--   * update_signups          a name and a phone number, an email, or both.
--   * submit_update_signup    the only way in, granted to anon. Never raises
--                             for anything a person could have done; returns
--                             {ok, status, message} for the page to show.
--   * admin_update_signups()  the list, for #/ops?tab=quiz's subscriber CSV,
--                             admin only (0016's gate in the body).
--
-- THE SAME TRADE AS 0067, stated again because it is a second anon write: no
-- table grants, a honeypot, a row cap, and no per-address limit (carrier-grade
-- NAT puts many Malawian subscribers behind one address). One row per phone
-- and one per email, by partial unique indexes, so a second sign-up from the
-- same person is "already on the list", never a duplicate row.
--
-- Signing up IS the consent: the box says what it is for and that it can be
-- stopped, and there is nothing else on it to agree to. Like quiz_entries,
-- none of this is in the Dataset or data/canonical/.

begin;

create table public.update_signups (
  id         bigint generated by default as identity primary key,
  name       text not null,
  -- quiz_normalise_phone's form (+265…), or '' when only an email was given.
  phone      text not null default '',
  email      text not null default '',
  -- Where the box was: 'quiz' today. Free text, nothing reads meaning into it.
  source     text not null default 'quiz',
  created_at timestamptz not null default now(),
  check (phone <> '' or email <> '')
);

create unique index update_signups_phone on public.update_signups (phone)
  where phone <> '';
create unique index update_signups_email on public.update_signups (email)
  where email <> '';

comment on table public.update_signups is
  'People who asked to hear about future quizzes and events (0071). Written '
  'only by submit_update_signup, read by admin_update_signups. Never in the '
  'Dataset.';

alter table public.update_signups enable row level security;
revoke all on public.update_signups from anon, authenticated;


create or replace function public.submit_update_signup(
  p_name    text,
  p_phone   text default '',
  p_email   text default '',
  p_website text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_name  text;
  v_phone text := '';
  v_email text;
begin
  if coalesce(p_website, '') <> '' then
    return jsonb_build_object('ok', true, 'status', 'signed_up');
  end if;

  v_name := left(btrim(regexp_replace(coalesce(p_name, ''), '\s+', ' ', 'g')),
                 80);
  if length(v_name) < 2 then
    return jsonb_build_object('ok', false, 'status', 'invalid',
      'message', 'Please enter your name.');
  end if;

  if btrim(coalesce(p_phone, '')) <> '' then
    v_phone := public.quiz_normalise_phone(p_phone);
    if v_phone is null then
      return jsonb_build_object('ok', false, 'status', 'invalid',
        'message', 'That phone number does not look right, '
                   'like 0991 234 567. Fix it, or leave it empty.');
    end if;
  end if;

  v_email := lower(btrim(coalesce(p_email, '')));
  if v_email <> '' and (length(v_email) > 120
                        or v_email !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$') then
    return jsonb_build_object('ok', false, 'status', 'invalid',
      'message', 'That email address does not look right. '
                 'Fix it, or leave it empty.');
  end if;

  if v_phone = '' and v_email = '' then
    return jsonb_build_object('ok', false, 'status', 'invalid',
      'message', 'Please give a phone number or an email address, '
                 'so we can reach you.');
  end if;

  if exists (select 1 from public.update_signups s
             where (v_phone <> '' and s.phone = v_phone)
                or (v_email <> '' and s.email = v_email)) then
    return jsonb_build_object('ok', true, 'status', 'already',
      'message', 'You are already on the list. We will be in touch.');
  end if;

  if (select count(*) from public.update_signups) >= 50000 then
    return jsonb_build_object('ok', false, 'status', 'full',
      'message', 'Sorry, we cannot take more sign-ups right now.');
  end if;

  begin
    insert into public.update_signups (name, phone, email)
    values (v_name, v_phone, v_email);
  exception when unique_violation then
    -- Two taps on a slow connection: the first one got in.
    return jsonb_build_object('ok', true, 'status', 'already',
      'message', 'You are already on the list. We will be in touch.');
  end;

  return jsonb_build_object('ok', true, 'status', 'signed_up');
end;
$$;

comment on function public.submit_update_signup(text, text, text, text) is
  'Sign up for news of future quizzes and events (0071). Granted to anon; '
  'never raises for bad input, returns {ok, status, message}.';

revoke execute on function public.submit_update_signup(text, text, text, text)
  from public;
grant execute on function public.submit_update_signup(text, text, text, text)
  to anon, authenticated;


create or replace function public.admin_update_signups()
returns table (
  id         bigint,
  created_at timestamptz,
  name       text,
  phone      text,
  email      text,
  source     text
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'Only an administrator can see the sign-up list.'
      using errcode = '42501';
  end if;
  return query
  select s.id, s.created_at, s.name, s.phone, s.email, s.source
  from public.update_signups s
  order by s.created_at;
end;
$$;

revoke execute on function public.admin_update_signups() from public, anon;
grant execute on function public.admin_update_signups() to authenticated;

commit;
